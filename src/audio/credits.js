// Sound credits from public/audio/manifest.json (stories 6.4 and 6.12).
// Pure functions, no DOM: shared by scripts/build-audio.mjs (manifest check
// and the README block), the tests and the page's Credits list (src/credits.js).

// D-6.2 narrowed by D-6.6: open licences only, no CC BY-NC.
export const ALLOWED_LICENCES = ['CC0', 'CC BY 3.0', 'CC BY 4.0', 'CC BY-SA 4.0'];

export const LICENCE_URLS = {
  'CC0': 'https://creativecommons.org/publicdomain/zero/1.0/',
  'CC BY 3.0': 'https://creativecommons.org/licenses/by/3.0/',
  'CC BY 4.0': 'https://creativecommons.org/licenses/by/4.0/',
  'CC BY-SA 4.0': 'https://creativecommons.org/licenses/by-sa/4.0/',
};

export const CREDIT_FIELDS = ['title', 'recordist', 'url', 'licence', 'edited'];

// Live weather (D-1.1), shown in the same list while it's used (D-0.5).
export const WEATHER_CREDIT = {
  title: 'Weather data',
  recordist: 'Open-Meteo.com',
  url: 'https://open-meteo.com/',
  licence: 'CC BY 4.0',
};

// Every problem with the manifest, as readable lines; [] when it's good.
export function checkManifest(manifest) {
  const out = [];
  const sounds = manifest?.sounds;
  if (!sounds || typeof sounds !== 'object' || !Object.keys(sounds).length) return ['no sounds'];
  const sr = manifest.sampleRate;
  if (!Number.isInteger(sr) || sr <= 0) out.push('sampleRate missing');
  for (const [id, s] of Object.entries(sounds)) {
    if (!['bed', 'event', 'thunder'].includes(s.role)) out.push(`${id}: role "${s.role}"`);
    if (!Array.isArray(s.scenes) || !s.scenes.length) out.push(`${id}: no scenes`);
    if (!Array.isArray(s.files) || !s.files.length) out.push(`${id}: no files`);
    for (const f of s.files || []) {
      if (!f.webm || !f.m4a) out.push(`${id}: a file without webm and m4a`);
      if (!(f.seconds > 0)) out.push(`${id}: ${f.webm} has no duration`);
      if (!Number.isInteger(f.samples) || f.samples <= 0) out.push(`${id}: ${f.webm} has no sample count`);
    }
    if (s.role === 'bed') {
      const L = s.loop;
      if (!L || !Number.isInteger(L.startSample) || !Number.isInteger(L.endSample) || L.endSample <= L.startSample) {
        out.push(`${id}: bed without loop points in samples`);
      } else if (L.endSample > s.files[0].samples) out.push(`${id}: loop ends after the file`);
    }
    const c = s.credit || {};
    for (const k of CREDIT_FIELDS) if (typeof c[k] !== 'string' || !c[k].trim()) out.push(`${id}: credit.${k} missing`);
    if (c.licence && !ALLOWED_LICENCES.includes(c.licence)) out.push(`${id}: licence "${c.licence}" is not allowed (D-6.6)`);
    if (c.url && !/^https:\/\//.test(c.url)) out.push(`${id}: credit.url is not https`);
  }
  return out;
}

// One entry per recording (a recording cut into several files is credited
// once), in manifest order, with the files it became.
export function soundCredits(manifest) {
  const byUrl = new Map();
  for (const [id, s] of Object.entries(manifest?.sounds || {})) {
    const c = s.credit;
    if (!c) continue;
    const files = (s.files || []).flatMap((f) => [f.webm, f.m4a]);
    const seen = byUrl.get(c.url);
    if (seen) { seen.ids.push(id); seen.files.push(...files); continue; }
    byUrl.set(c.url, {
      ids: [id], title: c.title, recordist: c.recordist, url: c.url, licence: c.licence,
      licenceUrl: LICENCE_URLS[c.licence] || null, edited: c.edited, attribution: c.licence !== 'CC0', files,
    });
  }
  return [...byUrl.values()];
}

const START_TAG = '<!-- sound-credits:start';
export const README_START = START_TAG + ' (generated by scripts/build-audio.mjs from public/audio/manifest.json; do not edit) -->';
export const README_END = '<!-- sound-credits:end -->';

// The README's "Sound credits" block (between the markers, markers included).
export function readmeCreditsBlock(manifest) {
  const md = (t) => String(t).replace(/([\\[\]*_`|])/g, '\\$1');
  const lines = soundCredits(manifest).map((e) => {
    const lic = e.licenceUrl ? `[${e.licence}](${e.licenceUrl})` : e.licence;
    const files = e.files.filter((f) => f.endsWith('.webm')).map((f) => '`' + f.replace(/\.webm$/, '') + '`').join(', ');
    return `- [${md(e.title)}](${e.url}) by ${md(e.recordist)}, ${lic}; ${e.edited}. Files: ${files} (.webm and .m4a).`;
  });
  return [README_START, ...lines, README_END].join('\n');
}

// Swap the block into the README text. Throws if the markers are missing.
export function withReadmeCredits(readme, manifest) {
  const a = readme.indexOf(START_TAG), b = readme.indexOf(README_END);
  if (a < 0 || b < a) throw new Error('README has no sound-credits markers');
  return readme.slice(0, a) + readmeCreditsBlock(manifest) + readme.slice(b + README_END.length);
}

const esc = (t) => String(t).replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));

function itemHtml(e) {
  const link = (href, text) => `<a href="${esc(href)}" target="_blank" rel="noopener">${esc(text)}</a>`;
  const lic = e.licenceUrl ? link(e.licenceUrl, e.licence) : esc(e.licence);
  return `<li>${link(e.url, e.title)} <span class="by">by ${esc(e.recordist)}</span>, ${lic}</li>`;
}

// The page's list: sounds, then the weather data while live weather is on.
export function creditsHtml(manifest, { weather = false } = {}) {
  const sounds = soundCredits(manifest);
  const parts = [];
  if (sounds.length) {
    parts.push('<h3>Sounds</h3>', `<ul>${sounds.map(itemHtml).join('')}</ul>`,
      '<p class="note">Recordings trimmed and levelled for this site; background sounds looped.</p>');
  }
  if (weather) parts.push('<h3>Weather</h3>', `<ul>${itemHtml({ ...WEATHER_CREDIT, licenceUrl: LICENCE_URLS[WEATHER_CREDIT.licence] })}</ul>`);
  return parts.join('');
}
