// Linear interpolation into a curve. u: 0..1 through the cycle (wraps).
export function sampleGait(curve, u) {
  const x = (((u % 1) + 1) % 1) * 100;
  const i = Math.floor(x);
  const f = x - i;
  return curve[i] + (curve[Math.min(100, i + 1)] - curve[i]) * f;
}
